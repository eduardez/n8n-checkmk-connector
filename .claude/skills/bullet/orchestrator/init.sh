#!/usr/bin/env bash
# init.sh — BT-01: plug bullet into a repo. Creates .bullet/, config, per-repo skill,
# gitignore lines, labels (with notice), runs doctor, prints the cron line.
# shellcheck shell=bash
set -u
BULLET_HOME="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
. "$BULLET_HOME/lib/config.sh"

T=$(cd "${1:?usage: bullet init <repo-dir>}" && pwd)
[[ -d $T/.git ]] || { echo "bullet: $T is not a git repo"; exit 1; }

mkdir -p "$T/.bullet"

# 1. config (never overwrite an existing one)
if [[ ! -f $T/.bullet/bullet.yaml ]]; then
  forge=https://git.eduard3v.com; repo=""
  if remote=$(git -C "$T" remote get-url origin 2>/dev/null); then
    case $remote in
      *git.eduard3v.com*) forge=https://git.eduard3v.com ;;
      *github.com*)       forge=https://api.github.com ;;
    esac
    repo=$(echo "$remote" | sed -E 's#.*[:/]([^/]+/[^/.]+)(\.git)?$#\1#')
  fi
  # trunk/ship from the remote's HEAD branch — a repo whose trunk is `main` must not get the
  # develop/main template (worktree add would target a nonexistent origin/develop).
  default_branch=$(git -C "$T" remote show origin 2>/dev/null | awk '/HEAD branch/{print $NF}')
  default_branch=${default_branch:-main}
  sed -e "s|^  trunk: .*|  trunk: $default_branch   # PRs land here (from remote HEAD)|" \
      -e "s|^  ship: .*|  ship: $default_branch|" \
      -e "s|forge: .*|forge: forgejo|" -e "s|url: .*|url: $forge|" \
      -e "s|repo: .*|repo: ${repo:-owner/name}|" \
      "$BULLET_HOME/bullet.yaml.example" > "$T/.bullet/bullet.yaml"
  echo "init: wrote $T/.bullet/bullet.yaml (trunk/ship from remote: $default_branch — edit gates/models/agents)"
else
  echo "init: keeping existing $T/.bullet/bullet.yaml"
fi

# 2. per-repo skill (regenerated each init; safe to customize afterwards)
repo_slug=$(basename "$T")
BULLET_CFG_FILE=$T/.bullet/bullet.yaml
trunk=$(. "$BULLET_HOME/lib/config.sh" >/dev/null 2>&1; cfg branches.trunk "$BULLET_CFG_FILE" 2>/dev/null)
trunk=${trunk:-main}
cat > "$T/.bullet/AGENT.md" <<EOF
---
name: bullet-fleet-$repo_slug
description: Use when running bullet on this repo, draining its issue queue, or checking the fleet. Per-repo skill generated by bullet init.
---

# bullet fleet — $repo_slug

Config: \`.bullet/bullet.yaml\` (forge, repo, trunk/ship, agents ≤10, models, gates, budgets).
Runtime: \`.bullet/{state,meta,worktrees,logs}\` — gitignored. The forge labels are the state
machine; the forge is the only database.

## Commands

\`\`\`bash
bullet doctor  $T    # readiness: deps, auth, config, forge, labels, omp
bullet status  $T    # fleet overview: issues per state + live sessions
bullet tick    $T    # one orchestration action (safe to repeat; idempotent)
\`\`\`

Auth: \`BULLET_TOKEN\` (bot account preferred) or \`BULLET_BASIC=user:pass\` env — never in files.

## Operating loop (agent replaces cron)

1. \`bullet status\` — orient.
2. \`bullet tick\` — one action: preflight → maybe launch → maybe transition → maybe reviewer →
   maybe integrate → maybe publish.
3. Repeat tick until the queue is drained (nothing in queued/running/review, no live sessions).
   Do NOT stop early or hand back while work remains.
4. Post the final summary: per-issue outcomes (PR number, what changed), key decisions the
   agents made, anything blocked, and that merging the PRs into trunk is the human's move.

## Integration branch

Reviewed work is merged into \`bullet-develop\` by the orchestrator (gates on the merged tree,
never push red). Conflicts spawn a conflict-solver agent that owns the integration worktree
until it pushes. Trunk is never touched by agents — PRs to trunk wait for the human.

## Label law (BT-02)

If the five state labels (\`bullet:queued running review done blocked\`) are missing, bullet
**announces first, then creates them** — never silently. Interactive runs: the notice goes to
stdout. Unattended ticks: a comment lands on the oldest queued issue. Never remove this notice.

## Repo law (from bullet.yaml)

- trunk \`$trunk\` gets the PRs; humans merge; issues close by human hand.
- Branch protection (\`bullet protect $T --repair\`): trunk + bullet-develop push-blocked at the
  forge. A rejected push to a protected branch is the law working, not a bug — open a PR.
- gates: run by coder, re-run at publish; never weakened.
- \`Refs #N\` only — closing keywords banned.
EOF

# 3. gitignore runtime dirs
gi="$T/.gitignore"
touch "$gi"
for line in ".bullet/state/" ".bullet/meta/" ".bullet/worktrees/" ".bullet/logs/"; do
  grep -qxF "$line" "$gi" || echo "$line" >> "$gi"
done
echo "init: gitignore updated (state/meta/worktrees/logs ignored; config+skill stay committed)"

# 4. labels (with notice) + branch protection audit + doctor
. "$BULLET_HOME/lib/forge.sh"
. "$BULLET_HOME/lib/state.sh"
if [[ -n ${BULLET_TOKEN:-}${BULLET_BASIC:-} ]]; then
  bullet_load_config "$T"
  bullet_ensure_labels
  # BT-05: branching law lives at the forge, not in prompts. Audit now (report-only);
  # `bullet protect $T --repair` creates the rules. Never silent.
  echo "init: checking branch protection on trunk + bullet-develop (agents must never push trunk)"
  "$BULLET_HOME/orchestrator/protect.sh" "$T" || \
    echo "init: NOT enforced yet — run: bullet protect $T --repair (needs admin token)"
else
  echo "init: set BULLET_TOKEN or BULLET_BASIC, then run: bullet labels init $T && bullet doctor $T"
fi

echo
echo "init: done — wire the cron line (or let your agent tick):"
echo "  */30 * * * * BULLET_TOKEN=… bullet tick $T >> $T/.bullet/logs/tick.log 2>&1"
